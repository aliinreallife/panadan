#!/usr/bin/env bash
# Manage only Panadan's standalone, opt-in PostgreSQL 18 database.
# No Odoo source configuration or VPN credentials are loaded.
set -euo pipefail
umask 077
cd "$(dirname "$0")/.."

ENV_FILE=.env.platform
COMPOSE_FILE=compose.platform.yaml
BACKUP_DIR=data/platform-backups

fail() {
  echo "Panadan platform DB: $*" >&2
  exit 1
}
need_docker() {
  command -v docker >/dev/null 2>&1 || fail "Docker is required."
  docker compose version >/dev/null 2>&1 || fail "Docker Compose v2 is required."
}
check_env() {
  [[ -s "$ENV_FILE" && ! -L "$ENV_FILE" ]] || fail "Missing or symlinked $ENV_FILE. Run ./panadan.sh platform-db setup."
  local mode
  mode="$(stat -c '%a' "$ENV_FILE")" || fail "Cannot inspect $ENV_FILE permissions."
  (( (8#$mode & 8#077) == 0 )) || fail "$ENV_FILE must not be group/world accessible (chmod 600)."
  [[ "$(grep -Ec '^PANADAN_PLATFORM_DB_PASSWORD=' "$ENV_FILE")" == "1" ]] ||
    fail "$ENV_FILE must contain exactly one platform DB password."
  grep -Eq '^PANADAN_PLATFORM_DB_PASSWORD=[[:xdigit:]]{64}$' "$ENV_FILE" ||
    fail "$ENV_FILE must contain a 64-character hexadecimal secret generated by setup."
}
compose() {
  env -u PANADAN_PLATFORM_DB_PASSWORD docker compose --env-file "$ENV_FILE" -f "$COMPOSE_FILE" "$@"
}
require_up() {
  local id
  id="$(compose ps -q db)" || fail "Could not inspect platform database."
  [[ -n "$id" ]] || fail "Platform database is not running. Run ./panadan.sh platform-db up."
  [[ "$(docker inspect --format '{{.State.Running}}' "$id")" == "true" ]] ||
    fail "Platform database container is not running."
}
run_psql() {
  compose exec -T db psql -X -v ON_ERROR_STOP=1 -U panadan_owner -d panadan "$@"
}
assert_pg18() {
  local major
  major="$(run_psql -A -t -c 'SHOW server_version_num;')"
  [[ "$major" =~ ^18[[:digit:]]{4}$ ]] ||
    fail "Expected PostgreSQL 18, refusing to operate on an unexpected database version."
}
assert_schema() {
  local count
  count="$(run_psql -A -t -c "SELECT count(*) FROM information_schema.tables
    WHERE table_schema = 'panadan_ingest'
      AND table_name IN ('sources','source_records','raw_revisions','processing_jobs',
                         'derived_facts','sync_checkpoints','sync_runs')
      AND table_type = 'BASE TABLE';")"
  [[ "$count" == "7" ]] || fail "Platform schema is incomplete; initialize/check the migration."
}
case "${1:-help}" in
  setup)
    [[ ! -e "$ENV_FILE" ]] || fail "$ENV_FILE already exists; refusing to overwrite credentials."
    command -v openssl >/dev/null 2>&1 || fail "openssl is required to generate a strong secret."
    secret="$(openssl rand -hex 32)"
    tmp="$(mktemp ".env.platform.tmp.XXXXXXXX")"
    trap 'rm -f -- "$tmp"' EXIT
    printf 'PANADAN_PLATFORM_DB_PORT=15433\nPANADAN_PLATFORM_DB_PASSWORD=%s\n' "$secret" > "$tmp"
    chmod 600 "$tmp"
    ln -- "$tmp" "$ENV_FILE" || fail "Could not create $ENV_FILE without overwriting an existing file."
    rm -f -- "$tmp"
    echo "Created $ENV_FILE (permissions 600). Secret is not printed."
    echo "Nothing has started or imported data."
    ;;
  up)
    need_docker; check_env
    compose up -d --wait db
    echo "Panadan-owned PostgreSQL 18 is running (localhost only)."
    ;;
  init)
    need_docker; check_env; require_up; assert_pg18
    echo "Applying additive schema to Panadan-owned PostgreSQL only ..."
    run_psql --single-transaction < database/migrations/001_multisource_foundation.sql >/dev/null
    assert_schema
    echo "Schema applied; no source ingestion was enabled."
    ;;
  check)
    need_docker; check_env; require_up; assert_pg18; assert_schema
    run_psql -A -t -c "SELECT 'pg_major=' || current_setting('server_version_num')::integer / 10000;
SELECT 'schema_present=' || (to_regnamespace('panadan_ingest') IS NOT NULL);
SELECT 'tables=' || count(*) FROM information_schema.tables
  WHERE table_schema = 'panadan_ingest' AND table_type = 'BASE TABLE';
SELECT 'source_count=' || count(*) FROM panadan_ingest.sources;
SELECT 'active_sources=' || count(*) FROM panadan_ingest.sources WHERE enabled;"
    ;;
  backup)
    need_docker; check_env; require_up; assert_pg18; assert_schema
    command -v openssl >/dev/null 2>&1 || fail "openssl is required for unique backup filenames."
    mkdir -p -- "$BACKUP_DIR"
    chmod 700 "$BACKUP_DIR"
    timestamp="$(date -u +%Y%m%dT%H%M%SZ)"
    archive="$(mktemp "$BACKUP_DIR/.panadan-$timestamp-XXXXXXXX.partial")"
    trap 'rm -f -- "$archive"' EXIT
    # pg_dump reads Panadan's local DB through its internal Unix socket.
    compose exec -T db pg_dump -U panadan_owner -d panadan -Fc > "$archive"
    [[ -s "$archive" ]] || fail "Backup is empty."
    compose exec -T db pg_restore --list < "$archive" >/dev/null
    final="$BACKUP_DIR/panadan-$timestamp-$(openssl rand -hex 4).dump"
    mv -- "$archive" "$final"
    chmod 600 "$final"
    echo "Backup created: $final (mode 600, ignored by Git)."
    echo "Backup contains data and remains on this machine; arrange encrypted off-host backups."
    ;;
  rotate-password)
    # Explicit owner-only password rotation for the isolated platform DB.
    # No source credentials are loaded, no volume is removed, and no secret
    # is passed as a command-line argument or written to stdout/stderr.
    set +x
    need_docker; check_env; require_up; assert_pg18
    command -v openssl >/dev/null 2>&1 || fail "openssl is required for password rotation."
    identity="$(run_psql -A -t -c "SELECT current_database() || ':' || current_user;" 2>/dev/null)" ||
      fail "Cannot verify database identity for rotation."
    [[ "$identity" == "panadan:panadan_owner" ]] ||
      fail "Refusing to rotate credentials for an unexpected database identity."

    # The staged configuration must remain in the same directory so the
    # subsequent rename is atomic on ordinary local filesystems.
    staged="$(mktemp ".env.platform.rotate.XXXXXXXX")" ||
      fail "Could not stage new private credentials."
    trap '[[ -z "${staged:-}" ]] || rm -f -- "$staged"' EXIT
    chmod 600 "$staged"
    new_secret="$(openssl rand -hex 32)" ||
      fail "Could not generate a new random password."
    [[ "$new_secret" =~ ^[[:xdigit:]]{64}$ ]] ||
      fail "Generated password format was invalid."
    while IFS= read -r line || [[ -n "$line" ]]; do
      case "$line" in
        PANADAN_PLATFORM_DB_PASSWORD=*)
          printf 'PANADAN_PLATFORM_DB_PASSWORD=%s\n' "$new_secret" >> "$staged" ;;
        *) printf '%s\n' "$line" >> "$staged" ;;
      esac
    done < "$ENV_FILE"

    # Apply the server change over local stdin, not through Docker argv.
    # Suppress server SQL diagnostics because some errors could reproduce
    # the submitted ALTER statement containing the secret.
    if ! printf "ALTER ROLE panadan_owner PASSWORD '%s';\n" "$new_secret" |
         run_psql --single-transaction >/dev/null 2>&1; then
      fail "PostgreSQL rejected password rotation; existing config was retained."
    fi

    if ! mv -- "$staged" "$ENV_FILE"; then
      # An OS rename error leaves the original credentials in the env file.
      # Best-effort restore the server password to avoid a split-brain state.
      previous_secret="$(sed -n 's/^PANADAN_PLATFORM_DB_PASSWORD=//p' "$ENV_FILE")"
      if ! printf "ALTER ROLE panadan_owner PASSWORD '%s';\n" "$previous_secret" |
           run_psql --single-transaction >/dev/null 2>&1; then
        fail "Configuration update failed and password rollback failed; recover via local owner socket."
      fi
      fail "Configuration update failed; database password restored to the previous value."
    fi
    staged=""
    unset new_secret
    check_env

    # POSTGRES_PASSWORD in a running container does not automatically change
    # when the role is altered; recreate only the isolated DB service.
    if ! compose up -d --wait --force-recreate db >/dev/null; then
      fail "Password changed, but the database container did not restart cleanly. Retry platform-db up; volume retained."
    fi
    authentication="$(compose exec -T db sh -c 'PGPASSWORD="$POSTGRES_PASSWORD" psql -X -At -v ON_ERROR_STOP=1 -h 127.0.0.1 -U panadan_owner -d panadan -c "SELECT 1"' 2>/dev/null)" ||
      fail "Password changed, but TCP authentication verification failed."
    [[ "$authentication" == "1" ]] ||
      fail "Password changed, but TCP authentication verification returned an unexpected result."
    echo "Platform DB owner password rotated and TCP authentication verified."
    echo "Private .env.platform updated (mode 600); database volume preserved."
    echo "Update any authorized clients using the previous owner password."
    ;;
  down)
    need_docker; check_env
    compose down
    echo "Platform DB stopped. Persistent volume retained (no -v)."
    ;;
  help|-h|--help)
    echo "Usage: ./panadan.sh platform-db {setup|up|init|check|backup|rotate-password|down}"
    echo "Only the isolated Panadan PostgreSQL 18 database is affected."
    ;;
  *)
    fail "Unknown command. Use ./panadan.sh platform-db help."
    ;;
esac
