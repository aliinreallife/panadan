-- Panadan-owned PostgreSQL 18: additive auth/audit schema.
-- Applies ONLY to isolated Panadan DB (panadan or disposable panadan_ci).
-- Deliberately does NOT connect to source Odoo or change FastAPI's live Store.
DO $guard$
BEGIN
  IF current_database() NOT IN ('panadan','panadan_ci') THEN
    RAISE EXCEPTION 'Refusing Panadan auth migration on database %',current_database();
  END IF;
  IF current_setting('server_version_num')::int / 10000 <> 18 THEN
    RAISE EXCEPTION 'Expected PostgreSQL 18 for auth schema';
  END IF;
END
$guard$;

CREATE SCHEMA IF NOT EXISTS panadan_auth;
REVOKE ALL ON SCHEMA panadan_auth FROM PUBLIC;

-- Application account IDs are kept exactly across the SQLite -> PG migration.
-- Profile IDs are new random stable identifiers allocated during migration.
CREATE TABLE IF NOT EXISTS panadan_auth.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username TEXT NOT NULL UNIQUE CHECK (char_length(username) BETWEEN 1 AND 80),
  password_hash TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin','analyst','reader','metrics')),
  grants TEXT,
  is_active INTEGER NOT NULL DEFAULT 1 CHECK (is_active IN (0,1)),
  profile_id TEXT NOT NULL UNIQUE
    CHECK (profile_id ~ '^prf_[A-Za-z0-9_-]{32,}$')
);

CREATE TABLE IF NOT EXISTS panadan_auth.sessions (
  token_hash TEXT PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES panadan_auth.users(id) ON DELETE RESTRICT,
  csrf TEXT NOT NULL,
  expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS auth_sessions_expiry
  ON panadan_auth.sessions(expires_at);

CREATE TABLE IF NOT EXISTS panadan_auth.access_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  token_hash TEXT NOT NULL UNIQUE,
  scope TEXT NOT NULL CHECK (scope IN ('api:read','api:sensitive','mcp:read')),
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  last_used BIGINT,
  owner_id BIGINT NOT NULL REFERENCES panadan_auth.users(id) ON DELETE RESTRICT
);

CREATE TABLE IF NOT EXISTS panadan_auth.oauth_identities (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  issuer TEXT NOT NULL,
  subject TEXT NOT NULL,
  user_id BIGINT NOT NULL REFERENCES panadan_auth.users(id) ON DELETE RESTRICT,
  created_at BIGINT NOT NULL,
  UNIQUE (issuer,subject),
  UNIQUE (issuer,user_id)
);

CREATE TABLE IF NOT EXISTS panadan_auth.transcript_access_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES panadan_auth.users(id) ON DELETE RESTRICT,
  surface TEXT NOT NULL CHECK (surface IN ('mcp','webmcp')),
  call_id BIGINT NOT NULL,
  char_limit INTEGER NOT NULL CHECK (char_limit BETWEEN 1 AND 6000),
  created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS auth_transcript_user_time
  ON panadan_auth.transcript_access_audit(user_id,created_at);

CREATE TABLE IF NOT EXISTS panadan_auth.activity_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT REFERENCES panadan_auth.users(id) ON DELETE RESTRICT,
  surface TEXT NOT NULL CHECK (surface IN ('dashboard','api','mcp','auth')),
  action TEXT NOT NULL,
  http_status INTEGER NOT NULL CHECK (http_status BETWEEN 100 AND 599),
  duration_ms INTEGER NOT NULL CHECK (duration_ms BETWEEN 0 AND 600000),
  created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS auth_activity_time ON panadan_auth.activity_events(created_at);
CREATE INDEX IF NOT EXISTS auth_activity_user_time ON panadan_auth.activity_events(user_id,created_at);

CREATE TABLE IF NOT EXISTS panadan_auth.login_throttle (
  username_hash TEXT PRIMARY KEY,
  failure_count INTEGER NOT NULL CHECK (failure_count >= 0),
  window_started BIGINT NOT NULL,
  next_allowed BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS auth_login_throttle_expiry
  ON panadan_auth.login_throttle(window_started);

CREATE TABLE IF NOT EXISTS panadan_auth.operator_directory (
  operator_name TEXT PRIMARY KEY,
  destination TEXT,
  team TEXT,
  updated_at BIGINT NOT NULL
);

-- No PUBLIC role may read the accounts, token hashes or audits. Provision a
-- separate restricted runtime role in a reviewed, later migration.
REVOKE ALL ON ALL TABLES IN SCHEMA panadan_auth FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA panadan_auth FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA panadan_auth REVOKE ALL ON TABLES FROM PUBLIC;
ALTER DEFAULT PRIVILEGES IN SCHEMA panadan_auth REVOKE ALL ON SEQUENCES FROM PUBLIC;
